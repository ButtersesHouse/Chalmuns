package output

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/ButtersesHouse/Chalmuns/internal/state"
)

const maxCLAUDERules = 30

// staleAfterPRs is how far behind the PR watermark a rule's last_seen_pr may
// fall before its rendered source line asks the reader to re-verify it. Keep
// in sync with the "Stale rules" threshold in SKILL.md Step 13.
const staleAfterPRs = 200

// Options controls optional output features.
type Options struct {
	// RAGHints adds a cursor-agent query hint after each rule in domain skill
	// files so the AI can retrieve live codebase examples at skill-use time.
	RAGHints bool
	// ClaudeMDPath is the explicit destination for CLAUDE.md. When empty,
	// defaults to <outputDir>/CLAUDE.md. Set this to place CLAUDE.md at any
	// path independently of where the skill files are written. The special
	// values "none" and os.DevNull suppress the CLAUDE.md output entirely.
	ClaudeMDPath string
	// SkillsDir is the explicit destination directory for per-domain skill
	// files. When empty, defaults to <outputDir>/.claude/skills. Set this to
	// decouple the skill files location from the CLAUDE.md location.
	SkillsDir string
	// AgentsMDPath is the destination for AGENTS.md (the agents.md convention
	// read by Codex and other coding agents that don't load CLAUDE.md or
	// .claude/skills). When empty, defaults to <outputDir>/AGENTS.md. The
	// special values "none" and os.DevNull suppress the output.
	AgentsMDPath string
}

// Write generates CLAUDE.md and per-domain skill files.
// outputDir establishes the default root for both outputs (backward compat):
//
//	CLAUDE.md  →  opts.ClaudeMDPath  (or <outputDir>/CLAUDE.md)
//	skills     →  opts.SkillsDir     (or <outputDir>/.claude/skills)
func Write(s state.State, outputDir string, opts Options) error {
	claudeMDPath := opts.ClaudeMDPath
	if claudeMDPath == "" {
		claudeMDPath = filepath.Join(outputDir, "CLAUDE.md")
	}
	skillsDir := opts.SkillsDir
	if skillsDir == "" {
		skillsDir = filepath.Join(outputDir, ".claude", "skills")
	}
	// "none" (or the null device) suppresses the CLAUDE.md output; writing
	// through atomicWrite to /dev/null would fail (and must never rename over
	// a device), so skip rather than write.
	if claudeMDPath != "none" && claudeMDPath != os.DevNull {
		if err := writeCLAUDEMD(s, claudeMDPath); err != nil {
			return err
		}
	}
	agentsMDPath := opts.AgentsMDPath
	if agentsMDPath == "" {
		agentsMDPath = filepath.Join(outputDir, "AGENTS.md")
	}
	if agentsMDPath != "none" && agentsMDPath != os.DevNull {
		if err := writeAgentsMD(s, agentsMDPath, skillsDir); err != nil {
			return err
		}
	}
	return writeSkillFiles(s, skillsDir, opts)
}

func writeCLAUDEMD(s state.State, path string) error {
	rules := approvedRules(s, "CLAUDE.md")
	if len(rules) == 0 {
		return nil
	}
	if len(rules) > maxCLAUDERules {
		rules = rules[:maxCLAUDERules]
	}

	var b strings.Builder
	b.WriteString("# Coding Conventions\n\n")
	b.WriteString("These conventions were extracted from PR review history.")
	b.WriteString(" See `.claude/pattern-learner/state.json` for provenance.\n\n")
	renderUniversalRules(&b, rules, "##")

	return atomicWrite(path, b.String())
}

// renderUniversalRules writes CLAUDE.md-targeted rules at the given heading level.
func renderUniversalRules(b *strings.Builder, rules []state.Rule, heading string) {
	for _, r := range rules {
		b.WriteString(fmt.Sprintf("%s %s\n\n", heading, r.Title))
		renderExamples(b, r, 1)
		b.WriteString(r.Rule + "\n\n")
		b.WriteString(fmt.Sprintf("_Source: %s_\n\n", sourceLabel(r)))
	}
}

// writeAgentsMD writes an AGENTS.md (https://agents.md — the cross-agent
// convention read by Codex, Cursor, Gemini CLI, and others). It carries the
// universal rules and, because those agents do not auto-load .claude/skills,
// an index routing them to each domain's skill file by glob.
func writeAgentsMD(s state.State, path, skillsDir string) error {
	universal := approvedRules(s, "CLAUDE.md")
	if len(universal) > maxCLAUDERules {
		universal = universal[:maxCLAUDERules]
	}

	type domainInfo struct {
		name  string
		globs []string
	}
	byDomain := map[string][]string{}
	for _, r := range s.Rules {
		if r.Status != "approved" || r.Target.Location == "CLAUDE.md" || r.Target.Location == "" {
			continue
		}
		byDomain[r.Target.Location] = append(byDomain[r.Target.Location], r.Target.FileGlob...)
	}
	var domains []domainInfo
	for name, globs := range byDomain {
		domains = append(domains, domainInfo{name, dedupeStrings(globs)})
	}
	sort.Slice(domains, func(i, j int) bool { return domains[i].name < domains[j].name })

	if len(universal) == 0 && len(domains) == 0 {
		return nil
	}

	// Never clobber a hand-written AGENTS.md: only overwrite a file this
	// generator produced (identified by its provenance line).
	if data, err := os.ReadFile(path); err == nil && !strings.Contains(string(data), "by pattern-learner") {
		fmt.Fprintf(os.Stderr,
			"warn: %s exists and was not generated by pattern-learner — leaving it untouched. "+
				"Pass --agents-md <other-path> to write elsewhere, or merge the conventions manually.\n", path)
		return nil
	}

	var b strings.Builder
	b.WriteString("# Coding Conventions\n\n")
	b.WriteString("Conventions extracted from this repo's PR review history by pattern-learner.")
	b.WriteString(" This file follows the AGENTS.md convention (https://agents.md) so any coding agent can use it.")
	b.WriteString(" See `.claude/pattern-learner/state.json` for provenance.\n\n")

	if len(universal) > 0 {
		b.WriteString("## Universal rules\n\n")
		b.WriteString("These apply to every file in the repository.\n\n")
		renderUniversalRules(&b, universal, "###")
	}

	if len(domains) > 0 {
		b.WriteString("## Domain conventions\n\n")
		b.WriteString("Rules scoped to parts of the codebase live in per-domain files (plain markdown).")
		b.WriteString(" Before editing files matching a domain's globs, read that domain's file and follow its links to the `examples/` or `rules/` companion files for code samples.\n\n")
		for _, d := range domains {
			ref := filepath.Join(skillsDir, d.name, "SKILL.md")
			if rel, err := filepath.Rel(filepath.Dir(path), ref); err == nil && !strings.HasPrefix(rel, "..") {
				ref = rel
			}
			scope := d.name
			if len(d.globs) > 0 {
				scope = "`" + strings.Join(d.globs, "`, `") + "`"
			}
			b.WriteString(fmt.Sprintf("- %s → `%s`\n", scope, ref))
		}
		b.WriteString("\n")
	}

	return atomicWrite(path, b.String())
}

func dedupeStrings(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if s != "" && !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

// writeSkillFiles writes per-domain skill files under skillsDir.
// skillsDir is the root under which per-domain subdirs are created (e.g.
// ".claude/skills" → ".claude/skills/api/SKILL.md").
func writeSkillFiles(s state.State, skillsDir string, opts Options) error {
	byDomain := map[string][]state.Rule{}
	for _, r := range s.Rules {
		if r.Status != "approved" || r.Target.Location == "CLAUDE.md" || r.Target.Location == "" {
			continue
		}
		d := r.Target.Location
		byDomain[d] = append(byDomain[d], r)
	}

	for domain, rules := range byDomain {
		if err := writeSkillFile(domain, rules, skillsDir, s.DomainDescriptions[domain], s.LastExtractedPRNumber, opts); err != nil {
			return err
		}
	}
	return nil
}

func writeSkillFile(domain string, rules []state.Rule, skillsDir string, override string, watermark int, opts Options) error {
	sort.Slice(rules, func(i, j int) bool {
		ri, rj := confidenceRank(rules[i].Confidence), confidenceRank(rules[j].Confidence)
		if ri != rj {
			return ri < rj
		}
		return rules[i].Title < rules[j].Title
	})

	globs := collectGlobs(rules)
	desc := buildDescription(domain, globs, override)
	skillDir := filepath.Join(skillsDir, domain)

	// examples/ and rules/ are generator-owned: regenerate from scratch so
	// renamed or removed rules leave no stale files behind.
	for _, sub := range []string{"examples", "rules"} {
		if err := os.RemoveAll(filepath.Join(skillDir, sub)); err != nil {
			return err
		}
	}

	slugs := ruleSlugs(rules)
	header := renderSkillHeader(domain, desc, globs, rules)

	// Examples always live in companion files (progressive disclosure): the
	// SKILL.md body is a recurring token cost once loaded, so it carries only
	// the imperative rules plus pointers the consuming agent follows at its
	// discretion when it wants the do/don't code.
	inline := header + renderInlineRules(rules, slugs, watermark, opts)
	if lineCount(inline) <= maxSkillLines {
		if err := writeExampleFiles(skillDir, rules, slugs); err != nil {
			return err
		}
		return atomicWrite(filepath.Join(skillDir, "SKILL.md"), inline)
	}

	// Very large skill: chunk per the Claude Code guidance ("Keep SKILL.md
	// under 500 lines. Move detailed reference material to separate files.").
	// SKILL.md becomes a rule index; each rule lives in rules/<slug>.md with
	// its examples inline (the chunk itself is loaded on demand), and the
	// chunk corpus doubles as a grep target for full-text lookup.
	if err := writeRuleChunks(skillDir, rules, slugs, watermark, opts); err != nil {
		return err
	}
	return atomicWrite(filepath.Join(skillDir, "SKILL.md"), header+renderRuleIndex(rules, slugs))
}

// maxSkillLines is the chunking threshold for a generated domain SKILL.md,
// with headroom under the documented limit ("Keep SKILL.md under 500 lines").
const maxSkillLines = 450

// maxExamplePairs caps rendered do/don't pairs; state caps the arrays at 4.
const maxExamplePairs = 4

func renderSkillHeader(domain, desc string, globs []string, rules []state.Rule) string {
	var b strings.Builder
	b.WriteString("---\n")
	b.WriteString(fmt.Sprintf("name: %s\n", domain))
	b.WriteString(fmt.Sprintf("description: %s\n", desc))
	// paths gates auto-loading to work on matching files, so chain-loading
	// several domain skills only ever pulls in the ones actually in play.
	if len(globs) > 0 {
		b.WriteString(fmt.Sprintf("paths: %s\n", strings.Join(globs, ", ")))
	}
	b.WriteString("---\n\n")
	b.WriteString(fmt.Sprintf("# %s Conventions\n\n", capitalize(domain)))

	if exemplary := exemplaryFiles(rules); len(exemplary) > 0 {
		b.WriteString("## Exemplary Files\n\n")
		b.WriteString("Read one of these before writing new code in this domain — they best represent the team's style:\n\n")
		for _, f := range exemplary {
			b.WriteString(fmt.Sprintf("- `%s`\n", f))
		}
		b.WriteString("\n")
	}
	return b.String()
}

func renderInlineRules(rules []state.Rule, slugs []string, watermark int, opts Options) string {
	var b strings.Builder
	b.WriteString("## Rules\n\n")
	b.WriteString("Rules with examples link a file under `examples/` — read it at your discretion for do/don't code and real instances before writing code the rule covers.\n\n")
	for i, r := range rules {
		b.WriteString(fmt.Sprintf("### %s\n\n", r.Title))
		b.WriteString(r.Rule + "\n\n")
		if hasExamples(r) {
			b.WriteString(fmt.Sprintf("_Examples: `examples/%s.md`_\n\n", slugs[i]))
		}
		writeSourceLine(&b, r, watermark)
		writeRAGHint(&b, r, opts)
	}
	return b.String()
}

// writeExampleFiles writes one examples/<slug>.md per rule that has examples,
// holding every do/don't pair plus real-instance refs.
func writeExampleFiles(skillDir string, rules []state.Rule, slugs []string) error {
	for i, r := range rules {
		if !hasExamples(r) {
			continue
		}
		var b strings.Builder
		b.WriteString(fmt.Sprintf("# Examples — %s\n\n", r.Title))
		b.WriteString(r.Rule + "\n\n")
		renderExamples(&b, r, maxExamplePairs)
		if err := atomicWrite(filepath.Join(skillDir, "examples", slugs[i]+".md"), b.String()); err != nil {
			return err
		}
	}
	return nil
}

// writeRuleChunks writes one rules/<slug>.md per rule for the chunked layout.
func writeRuleChunks(skillDir string, rules []state.Rule, slugs []string, watermark int, opts Options) error {
	for i, r := range rules {
		var b strings.Builder
		b.WriteString(fmt.Sprintf("# %s\n\n", r.Title))
		meta := fmt.Sprintf("**Confidence:** %s", r.Confidence)
		if len(r.Target.FileGlob) > 0 {
			meta += " · **Applies to:** `" + strings.Join(r.Target.FileGlob, "`, `") + "`"
		}
		b.WriteString(meta + "\n\n")
		renderExamples(&b, r, maxExamplePairs)
		b.WriteString(r.Rule + "\n\n")
		writeSourceLine(&b, r, watermark)
		writeRAGHint(&b, r, opts)
		if err := atomicWrite(filepath.Join(skillDir, "rules", slugs[i]+".md"), b.String()); err != nil {
			return err
		}
	}
	return nil
}

func renderRuleIndex(rules []state.Rule, slugs []string) string {
	var b strings.Builder
	b.WriteString("This skill is chunked to keep SKILL.md small: each rule lives in its own file under `rules/`, examples included. Find matching rules in the index below (by title or glob) and read only those files. For a full-text lookup, grep the `rules/` directory next to this file, e.g. `grep -ril \"<keyword>\" rules/`.\n\n")
	b.WriteString("## Rule Index\n\n")
	last := ""
	for i, r := range rules {
		if r.Confidence != last {
			b.WriteString(fmt.Sprintf("### %s\n\n", confidenceHeading(r.Confidence)))
			last = r.Confidence
		}
		line := fmt.Sprintf("- [%s](rules/%s.md)", r.Title, slugs[i])
		if len(r.Target.FileGlob) > 0 {
			line += " — `" + strings.Join(r.Target.FileGlob, "`, `") + "`"
		}
		b.WriteString(line + "\n")
	}
	b.WriteString("\n")
	return b.String()
}

func confidenceHeading(c string) string {
	switch c {
	case "stated":
		return "Stated (explicit preferences)"
	case "established":
		return "Established"
	case "emerging":
		return "Emerging"
	default:
		return capitalize(c)
	}
}

func writeSourceLine(b *strings.Builder, r state.Rule, watermark int) {
	prOrigin := r.Origin == "" || r.Origin == "pr-review"
	if prOrigin && watermark > 0 && r.LastSeenPR > 0 && watermark-r.LastSeenPR >= staleAfterPRs {
		b.WriteString(fmt.Sprintf("_Source: %s_ _(last seen: PR #%d — verify this convention is still current)_\n\n",
			sourceLabel(r), r.LastSeenPR))
		return
	}
	b.WriteString(fmt.Sprintf("_Source: %s_\n\n", sourceLabel(r)))
}

func writeRAGHint(b *strings.Builder, r state.Rule, opts Options) {
	if !opts.RAGHints {
		return
	}
	b.WriteString(fmt.Sprintf(
		"_Live examples: `cursor-agent -p --mode=ask \"Show me 3 real examples of '%s' in this codebase with file paths\"`_\n\n",
		r.Title,
	))
}

func hasExamples(r state.Rule) bool {
	return len(effectiveDoExamples(r)) > 0 || len(effectiveDontExamples(r)) > 0
}

// slugify converts a rule title to a filesystem-safe slug.
func slugify(title string) string {
	var out []rune
	lastDash := true // also trims leading dashes
	for _, r := range strings.ToLower(title) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			out = append(out, r)
			lastDash = false
		} else if !lastDash {
			out = append(out, '-')
			lastDash = true
		}
	}
	s := strings.Trim(string(out), "-")
	if len(s) > 60 {
		s = strings.Trim(s[:60], "-")
	}
	if s == "" {
		return "rule"
	}
	return s
}

// ruleSlugs returns one unique slug per rule (suffixing -2, -3, … on collision).
func ruleSlugs(rules []state.Rule) []string {
	seen := map[string]int{}
	out := make([]string, len(rules))
	for i, r := range rules {
		s := slugify(r.Title)
		seen[s]++
		if n := seen[s]; n > 1 {
			s = fmt.Sprintf("%s-%d", s, n)
		}
		out[i] = s
	}
	return out
}

func lineCount(s string) int {
	return strings.Count(s, "\n") + 1
}

// renderExamples writes do/don't example pairs (up to maxPairs) before rule prose.
// Prefers DoExamples/DontExamples (plural); falls back to DoExample/DontExample for
// rules created before plural support was added.
func renderExamples(b *strings.Builder, r state.Rule, maxPairs int) {
	dos := effectiveDoExamples(r)
	donts := effectiveDontExamples(r)

	if len(dos) == 0 && len(donts) == 0 {
		return
	}

	n := len(dos)
	if len(donts) > n {
		n = len(donts)
	}
	if n > maxPairs {
		n = maxPairs
	}

	for i := 0; i < n; i++ {
		if i < len(dos) {
			b.WriteString(fmt.Sprintf("**Do:**\n```%s\n%s\n```\n", dos[i].Language, dos[i].Code))
			if dos[i].FileRef != "" {
				b.WriteString(fmt.Sprintf("_Real instance: see %s_\n", dos[i].FileRef))
			}
			b.WriteString("\n")
		}
		if i < len(donts) {
			b.WriteString(fmt.Sprintf("**Don't:**\n```%s\n%s\n```\n\n", donts[i].Language, donts[i].Code))
		}
	}
}

func effectiveDoExamples(r state.Rule) []state.Example {
	if len(r.DoExamples) > 0 {
		return r.DoExamples
	}
	if r.DoExample != nil {
		return []state.Example{*r.DoExample}
	}
	return nil
}

func effectiveDontExamples(r state.Rule) []state.Example {
	if len(r.DontExamples) > 0 {
		return r.DontExamples
	}
	if r.DontExample != nil {
		return []state.Example{*r.DontExample}
	}
	return nil
}

// approvedRules returns approved rules for a given target location,
// sorted stated → established → emerging, then alphabetically by title.
func approvedRules(s state.State, location string) []state.Rule {
	var out []state.Rule
	for _, r := range s.Rules {
		if r.Status == "approved" && r.Target.Location == location {
			out = append(out, r)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		ri, rj := confidenceRank(out[i].Confidence), confidenceRank(out[j].Confidence)
		if ri != rj {
			return ri < rj
		}
		return out[i].Title < out[j].Title
	})
	return out
}

// confidenceRank returns the sort priority for a confidence level.
// Lower is higher priority: stated(0) > established(1) > emerging(2).
func confidenceRank(c string) int {
	switch c {
	case "stated":
		return 0
	case "established":
		return 1
	case "emerging":
		return 2
	default:
		return 3
	}
}

// sourceLabel returns the provenance text for a rule's "_Source: …_" line.
// Manual and discover-origin rules have no PR numbers, so they get a descriptive
// label instead of an empty PR list.
func sourceLabel(r state.Rule) string {
	switch r.Origin {
	case "manual":
		return "manually added"
	case "discover":
		return "discovered from codebase"
	default:
		if prs := prList(r.Sources); prs != "" {
			return "PRs " + prs
		}
		return "—"
	}
}

func prList(sources []state.Signal) string {
	seen := map[int]bool{}
	var nums []int
	for _, s := range sources {
		if !seen[s.PRNumber] {
			seen[s.PRNumber] = true
			nums = append(nums, s.PRNumber)
		}
	}
	sort.Ints(nums)
	parts := make([]string, len(nums))
	for i, n := range nums {
		parts[i] = fmt.Sprintf("#%d", n)
	}
	return strings.Join(parts, ", ")
}

// exemplaryFiles returns up to 3 file paths that appear most frequently as
// FileRef targets across the domain's rules. These are the files that best
// represent the domain's coding style and are listed in the skill file so
// the AI can read one for holistic style guidance beyond individual rules.
func exemplaryFiles(rules []state.Rule) []string {
	freq := map[string]int{}
	for _, r := range rules {
		for _, ex := range effectiveDoExamples(r) {
			if ex.FileRef == "" {
				continue
			}
			// Strip :Lline suffix to get the bare file path.
			path := ex.FileRef
			if idx := strings.LastIndex(path, ":L"); idx > 0 {
				path = path[:idx]
			}
			freq[path]++
		}
	}
	if len(freq) == 0 {
		return nil
	}

	type entry struct {
		path  string
		count int
	}
	var entries []entry
	for p, c := range freq {
		entries = append(entries, entry{p, c})
	}
	sort.Slice(entries, func(i, j int) bool {
		if entries[i].count != entries[j].count {
			return entries[i].count > entries[j].count
		}
		return entries[i].path < entries[j].path
	})

	max := 3
	if len(entries) < max {
		max = len(entries)
	}
	out := make([]string, max)
	for i := range out {
		out[i] = entries[i].path
	}
	return out
}

func collectGlobs(rules []state.Rule) []string {
	seen := map[string]bool{}
	var out []string
	for _, r := range rules {
		for _, g := range r.Target.FileGlob {
			if !seen[g] {
				seen[g] = true
				out = append(out, g)
			}
		}
	}
	return out
}

// buildDescription returns the SKILL.md frontmatter description for a domain.
// If override is non-empty, it is used directly (truncated if needed). Otherwise
// a generic fallback is constructed from the domain name and globs.
func buildDescription(domain string, globs []string, override string) string {
	if override != "" {
		// The override is model-supplied; a newline would break the YAML
		// frontmatter line it is rendered into.
		override = strings.Join(strings.Fields(override), " ")
		if len(override) > 200 {
			return override[:197] + "..."
		}
		return override
	}
	base := fmt.Sprintf("Coding conventions for %s", domain)
	if len(globs) > 0 {
		base += fmt.Sprintf(". Use when editing files matching: %s", strings.Join(globs, ", "))
	}
	if len(base) > 200 {
		base = base[:197] + "..."
	}
	return base
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func atomicWrite(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
